const DICTS: Record<Lang, Record<MessageKey, string>> = { en, zh };

export type T = (key: MessageKey | string, params?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  const dict = DICTS[lang];
  return (key, params = {}) => {
    const tpl = (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
    return tpl.replace(/\{(\w+)\}/g, (_, k) => (params[k] === undefined ? `{${k}}` : String(params[k])));
  };
}
